#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Three-flag rule: every podman call (teardown included) passes --root, --runroot and --tmpdir,
# all inside this spike's directories. Without --tmpdir podman shares the user's libpod tmpdir.
#
# S-06 (FR-046, FR-061, FR-069, IR-025, IR-026, R-005): does the Basic-tier
# display, audio and GPU grant give a non-software renderer on Wayland and X11
# in a rootless realm, and does a hand-written CDI spec expose the host NVIDIA
# proprietary driver (nvidia-smi, GL, Vulkan)?
#
#   spikes/s06_gpu.sh run        build the image, run the Basic and NVIDIA probes
#   spikes/s06_gpu.sh verdicts   recompute verdicts.txt from the logs in GINN_SPIKE_OUT
#   spikes/s06_gpu.sh teardown   remove spike containers, image, storage, CDI dir
#
# Every podman call uses the spike storage (--root, --runroot, --tmpdir), never the default
# storage. No root steps. Logs and the summary go to GINN_SPIKE_OUT (default
# ~/.cache/ginn-spike/s06). The CDI spec is generated by spikes/s06/nvidia-cdi.py.
set -euo pipefail

SELF="$(readlink -f "$0")"
SPIKE_DIR="$(dirname "$SELF")"
IMAGE=localhost/ginn-s06:debian-stable
CT_BASIC=s06-basic
CT_NV=s06-nv
UID_="$(id -u)"
XRD="${XDG_RUNTIME_DIR:-/run/user/$UID_}"
WAYLAND_DISPLAY="${WAYLAND_DISPLAY:-wayland-1}"
DISPLAY="${DISPLAY:-:0}"
export WAYLAND_DISPLAY DISPLAY
DATA="${XDG_DATA_HOME:-$HOME/.local/share}/ginn-spike-s06"
PM_ROOT="$DATA/podman"
PM_RUNROOT="$XRD/ginn-spike-s06"
PM_TMP="$PM_RUNROOT/libpod-tmp"
CDI_DIR="$DATA/cdi"
OUT="${GINN_SPIKE_OUT:-${XDG_CACHE_HOME:-$HOME/.cache}/ginn-spike/s06}"
REALM_RUN="/run/user/$UID_"

# Optional OCI runtime override (for example S06_RUNTIME=crun) if keep-groups needs it.
RT=()
if [[ -n "${S06_RUNTIME:-}" ]]; then RT=(--runtime "$S06_RUNTIME"); fi

INIT=()
GRANT=()
INIT_NOTE=""

say() { printf '%s\n' "$*" >&2; }
die() { say "s06: $*"; exit 1; }

pm() { podman --root "$PM_ROOT" --runroot "$PM_RUNROOT" --tmpdir "$PM_TMP" "$@"; }

# probe [--user U] CTR NAME CMD...: run CMD in CTR, keep its log, record rc. Never aborts.
probe() {
  local user="" rc=0
  if [[ "$1" == --user ]]; then user=$2; shift 2; fi
  local ctr=$1 name=$2
  shift 2
  pm exec ${user:+--user "$user"} "$ctr" "$@" >"$OUT/$name.log" 2>&1 || rc=$?
  printf '%s rc=%s\n' "$name" "$rc" >>"$OUT/summary.txt"
}

preflight() {
  command -v podman >/dev/null || die "podman not found"
  command -v python3 >/dev/null || die "python3 not found"
  [[ -S "$XRD/$WAYLAND_DISPLAY" ]] || die "no Wayland socket at $XRD/$WAYLAND_DISPLAY"
  local xnum="${DISPLAY#:}"; xnum="${xnum%%.*}"
  [[ -S "/tmp/.X11-unix/X$xnum" ]] || die "no X socket for $DISPLAY"
  [[ -e /dev/dri/renderD128 ]] || die "no /dev/dri render nodes"
  [[ -e /proc/driver/nvidia/version ]] || die "NVIDIA driver not loaded"
  local avail
  avail="$(awk '/MemAvailable/ {print $2}' /proc/meminfo)"
  (( avail >= 262144 )) || die "MemAvailable below 256 MiB"
}

build_image() {
  local ctx
  ctx="$(mktemp -d "$OUT/ctx.XXXX")"
  pm build -t "$IMAGE" -f "$SPIKE_DIR/Dockerfile.s06" "$ctx" >"$OUT/build.log" 2>&1
  rm -rf "$ctx"
}

# --init needs catatonit in the image or on the host. S-02 found it absent, so probe once.
probe_init() {
  if pm run --rm --init "$IMAGE" true >"$OUT/init-probe.log" 2>&1; then
    INIT=(--init)
    INIT_NOTE="--init accepted"
  else
    INIT=()
    INIT_NOTE="--init refused (catatonit absent), run without it: $(tail -1 "$OUT/init-probe.log")"
  fi
  printf 'init: %s\n' "$INIT_NOTE" >>"$OUT/summary.txt"
}

# Basic-tier grant (FR-061): display sockets, audio sockets, GPU device nodes, fonts and timezone read-only.
grant_args() {
  GRANT=(
    --userns keep-id
    --network host
    --device /dev/dri
    --group-add keep-groups
    --tmpfs "$REALM_RUN:mode=0700,U"
    -v "$XRD/$WAYLAND_DISPLAY:$REALM_RUN/$WAYLAND_DISPLAY"
    -v /tmp/.X11-unix:/tmp/.X11-unix
    -v /usr/share/fonts:/usr/share/fonts:ro
    -v /etc/localtime:/etc/localtime:ro
    -e WAYLAND_DISPLAY
    -e DISPLAY
    -e "XDG_RUNTIME_DIR=$REALM_RUN"
  )
  if [[ -n "${XAUTHORITY:-}" ]]; then
    GRANT+=(-v "$XAUTHORITY:$XAUTHORITY:ro" -e XAUTHORITY)
  fi
  local s
  for s in pipewire-0 pulse/native; do
    if [[ -S "$XRD/$s" ]]; then
      GRANT+=(-v "$XRD/$s:$REALM_RUN/$s")
    fi
  done
  printf 'host sockets: %s\n' "$(ls -1 "$XRD" | grep -E '^(wayland|pipewire|pulse|X)' | tr '\n' ' ' || true)" >>"$OUT/summary.txt"
}

start_basic() {
  pm run -d --name "$CT_BASIC" "${RT[@]}" "${INIT[@]}" "${GRANT[@]}" "$IMAGE" sleep infinity \
    >"$OUT/run-basic.log" 2>&1
}

basic_probes() {
  probe "$CT_BASIC" basic-id id
  probe "$CT_BASIC" basic-env env
  probe "$CT_BASIC" basic-ls ls -la "$REALM_RUN" /dev/dri
  probe "$CT_BASIC" basic-wayland-info wayland-info
  probe "$CT_BASIC" basic-eglinfo-wayland eglinfo -B -p wayland
  probe "$CT_BASIC" basic-eglinfo-default eglinfo -B
  probe "$CT_BASIC" basic-glx-x11 glxinfo -B
  probe "$CT_BASIC" basic-glx-dri-prime env DRI_PRIME=1 glxinfo -B
  probe "$CT_BASIC" basic-vulkan vulkaninfo --summary
  probe "$CT_BASIC" basic-glmark2 glmark2 --off-screen -b build:duration=2
  # Visible-window check: a 2 s run on Xwayland. rc 124 is the expected timeout.
  probe "$CT_BASIC" basic-glxgears timeout 2 glxgears
}

nvidia_spec() {
  python3 -I "$SPIKE_DIR/s06/nvidia-cdi.py" "$DATA" >"$OUT/nvidia-cdi.json" 2>"$OUT/nvidia-cdi.err" \
    || die "nvidia-cdi.py failed, see $OUT/nvidia-cdi.err"
}

start_nv() {
  pm --cdi-spec-dir "$CDI_DIR" run -d --name "$CT_NV" "${RT[@]}" "${INIT[@]}" "${GRANT[@]}" \
    --device nvidia.com/gpu=all "$IMAGE" sleep infinity >"$OUT/run-nv.log" 2>&1
}

nvidia_probes() {
  # ld search path, step by step: drop-in only (no ldconfig) first, then LD_LIBRARY_PATH, then ldconfig.
  probe "$CT_NV" nv-smi-dropin-only nvidia-smi
  probe "$CT_NV" nv-smi-ld-library-path env LD_LIBRARY_PATH=/usr/lib/ginn-nvidia nvidia-smi
  probe --user 0:0 "$CT_NV" nv-ldconfig ldconfig
  probe "$CT_NV" nv-smi-after-ldconfig nvidia-smi
  probe "$CT_NV" nv-smi-query nvidia-smi --query-gpu=name,driver_version --format=csv,noheader
  probe "$CT_NV" nv-glx-offload env __NV_PRIME_RENDER_OFFLOAD=1 __GLX_VENDOR_LIBRARY_NAME=nvidia glxinfo -B
  probe "$CT_NV" nv-glx-vendor env __GLX_VENDOR_LIBRARY_NAME=nvidia glxinfo -B
  probe "$CT_NV" nv-glx-default glxinfo -B
  probe "$CT_NV" nv-eglinfo-wayland env EGL_PLATFORM=wayland eglinfo -B -p wayland
  probe "$CT_NV" nv-vulkan vulkaninfo --summary
  probe "$CT_NV" nv-device-view ls -la /dev/nvidia0 /dev/nvidiactl /dev/nvidia-uvm /dev/nvidia-caps/
  probe "$CT_NV" nv-cap1-open sh -c "head -c0 /dev/nvidia-caps/nvidia-cap1 && echo readable || echo denied"
  probe "$CT_NV" nv-egl-surfaceless env __EGL_VENDOR_LIBRARY_FILENAMES=/usr/share/glvnd/egl_vendor.d/10_nvidia.json eglinfo -B -p surfaceless
  probe "$CT_NV" nv-egl-wayland-forced env EGL_PLATFORM=wayland __EGL_VENDOR_LIBRARY_FILENAMES=/usr/share/glvnd/egl_vendor.d/10_nvidia.json eglinfo -B -p wayland
}

# verdicts: renderer strings from the logs, PASS when the renderer is not software.
renderer_of() {  # renderer_of LOG: first GL renderer in the log (glxinfo or eglinfo)
  grep -m1 -E '^OpenGL (renderer string|core profile renderer): ' "$OUT/$1.log" 2>/dev/null \
    | sed -E 's/^OpenGL (renderer string|core profile renderer): //' || true
}

verdict_renderer() {  # verdict_renderer LABEL LOG
  local r
  r="$(renderer_of "$2")"
  if [[ -z "$r" ]]; then
    printf '%s: FAIL (no renderer string in %s)\n' "$1" "$2" >>"$OUT/verdicts.txt"
  elif [[ "$r" =~ llvmpipe|softpipe|swrast ]]; then
    printf '%s: FAIL (software renderer: %s)\n' "$1" "$r" >>"$OUT/verdicts.txt"
  else
    printf '%s: PASS (%s)\n' "$1" "$r" >>"$OUT/verdicts.txt"
  fi
}

verdicts() {
  : >"$OUT/verdicts.txt"
  verdict_renderer "FR-046 Wayland" basic-eglinfo-wayland
  verdict_renderer "FR-046 X11" basic-glx-x11
  local drv smi_ok="FAIL"
  drv="$(grep -oE '[0-9]{3}\.[0-9]+\.[0-9]+' /proc/driver/nvidia/version | head -1)"
  if grep -q "Driver Version: $drv" "$OUT/nv-smi-after-ldconfig.log" 2>/dev/null \
     && grep -q 'RTX 2050' "$OUT/nv-smi-after-ldconfig.log" 2>/dev/null; then
    smi_ok="PASS"
  fi
  printf 'FR-069: %s (host driver %s, realm nvidia-smi shows it and the GPU)\n' "$smi_ok" "$drv" >>"$OUT/verdicts.txt"
}

run() {
  preflight
  mkdir -p "$OUT" "$DATA" "$CDI_DIR" "$PM_TMP"
  chmod 700 "$DATA"
  : >"$OUT/summary.txt"
  build_image
  probe_init
  grant_args
  start_basic
  basic_probes
  nvidia_spec
  start_nv
  nvidia_probes
  verdicts
  say "s06: logs in $OUT. Read summary.txt and verdicts.txt, then run: $0 teardown"
}

teardown() {
  pm rm -f -t 0 "$CT_BASIC" "$CT_NV" >/dev/null 2>&1 || true
  pm rmi -f "$IMAGE" >/dev/null 2>&1 || true
  pm unshare rm -rf "$PM_ROOT" >/dev/null 2>&1 || true
  rm -rf "$PM_RUNROOT" "$CDI_DIR" "$DATA/ld"
  rm -rf "$DATA"
  say "s06: teardown done (containers, image, storage root, runroot, CDI dir)"
}

case "${1:-}" in
  run) run ;;
  verdicts) verdicts ;;
  teardown) teardown ;;
  *) die "usage: $0 run|verdicts|teardown" ;;
esac
