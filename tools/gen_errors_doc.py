"""Write docs/errors.md from the error catalogue in src/ginn/errors.py (NFR-040).

Run with --check to exit 1 when docs/errors.md differs from the catalogue; nothing is written.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from ginn.errors import ErrorSpec

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "errors.md"
HEADER = (
    "# Error catalogue\n"
    "\n"
    "Generated by `tools/gen_errors_doc.py` from `src/ginn/errors.py`. Do not edit by hand.\n"
    "\n"
    "Placeholders in braces, such as `{name}`, are filled in at run time.\n"
    "\n"
    "Exit status 125 is not used by any code below. `ginn exec` returns the inner command's exit "
    "status, so ginn-side failures of `exec` and `enter` exit 125 instead (IR-011, FR-049).\n"
    "Only a `GINN-E-` line on stderr, or a JSON error object, marks a ginn failure of `exec` or "
    "`enter`. A 125 that podman or the command returns on its own is passed through unchanged, so "
    "the exit status alone does not tell the two apart. The exceptions are the argparse refusals "
    "(exit 2) and Ctrl-C (130).\n"
    "\n"
)


def _load() -> tuple[list[ErrorSpec], tuple[tuple[int, str], ...]]:
    """Return the catalogue entries and the exit-status categories from src/ginn/errors.py."""
    sys.path.insert(0, str(ROOT / "src"))
    from ginn.errors import CATALOGUE, EXIT_CATEGORIES

    return list(CATALOGUE.values()), EXIT_CATEGORIES


def _cell(text: str) -> str:
    """Escape a plain-text table cell: pipes split cells, angle brackets read as HTML tags."""
    return text.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def _template(text: str) -> str:
    """Show a catalogue template as written: doubled braces are literal braces in the output."""
    return text.replace("{{", "{").replace("}}", "}")


def _exit_table(categories: Iterable[tuple[int, str]]) -> str:
    """Render the exit-status categories as a two-column table."""
    rows = ["| Exit | Meaning |", "|---|---|"]
    rows.extend(f"| {status} | {_cell(meaning)} |" for status, meaning in categories)
    return "\n".join(rows) + "\n"


def render(specs: Iterable[ErrorSpec], categories: Iterable[tuple[int, str]]) -> str:
    """Return the text of docs/errors.md: the exit categories, then the catalogue by code."""
    specs = list(specs)
    categories = list(categories)
    listed = {status for status, _meaning in categories}
    unlisted = sorted({spec.exit_code for spec in specs} - listed)
    if unlisted:
        raise ValueError(f"catalogue exit statuses {unlisted} are missing from EXIT_CATEGORIES")
    rows = ["| Code | Exit | Meaning | Remedy | Source |", "|---|---|---|---|---|"]
    for spec in sorted(specs, key=lambda item: item.code):
        # The code is inside a code span, so it is not escaped.
        cells = [
            f"`{spec.code}`",
            str(spec.exit_code),
            _cell(_template(spec.summary)),
            _cell(_template(spec.remedy)),
            _cell(spec.source),
        ]
        rows.append("| " + " | ".join(cells) + " |")
    return (
        HEADER
        + "## Exit statuses\n\n"
        + _exit_table(categories)
        + "\n## Codes\n\n"
        + "\n".join(rows)
        + "\n"
    )


def main(argv: list[str] | None = None) -> int:
    """Generate docs/errors.md, or with --check verify that it is current."""
    parser = argparse.ArgumentParser(
        prog="gen_errors_doc.py",
        description="Write docs/errors.md from the error catalogue.",
        epilog="Example: python3 tools/gen_errors_doc.py --check",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if docs/errors.md is out of date; write nothing",
    )
    args = parser.parse_args(argv)
    specs, categories = _load()
    text = render(specs, categories)
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            sys.stderr.write(f"{TARGET} is out of date; run tools/gen_errors_doc.py\n")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
