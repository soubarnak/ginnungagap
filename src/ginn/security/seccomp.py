"""The seccomp profile of a Development realm: the default profile, with `sethostname` allowed.

ADR-006 and FR-062 AC-3. The inner crun calls `sethostname`, and the default profile refuses that
call without CAP_SYS_ADMIN, which a realm never holds. The profile here is the host's default
profile (`/usr/share/containers/seccomp.json`, from `containers-common`), changed in one place:

1. Remove the name `sethostname` from every rule that names it. A rule left with no names is
   dropped. `setdomainname` is left as it is (S-07e Finding 3).
2. Insert one rule at the front that allows `sethostname` with no conditions.
3. Change nothing else.

Fail closed. The generator refuses (GINN-E-SECCOMP-SOURCE) a source that is missing, unreadable, not
a profile, or names no `sethostname`. It also refuses a source whose `defaultAction` is not a deny
action, and a rule it cannot check: the old single `name` field, or a rule with no `names` list. A
refused source is never replaced by `seccomp=unconfined` (ADR-006).

The file is named by the SHA-256 of its generated bytes, so a changed host profile or a changed
generator gives a new file (DR-010). `write` makes the file if it is absent. An existing file must
be a regular file (not a link): its bytes are compared with the plan, and a different one is
replaced atomically. Only `plan` reads the source, so a plan refused before the create writes
nothing.
"""

import hashlib
import json
import os
import stat
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

from ginn.errors import GinnError, make
from ginn.store.paths import OWNED_DIR_MODE, write_bytes_atomic

DEFAULT_SOURCE: Final = Path("/usr/share/containers/seccomp.json")
"""The host's default profile, which podman uses. Its owner is the `containers-common` package."""
SETHOSTNAME: Final = "sethostname"
ALLOW_COMMENT: Final = "ginn: sethostname for nested containers (ADR-006)"
DENY_ACTIONS: Final[frozenset[str]] = frozenset(
    {
        "SCMP_ACT_ERRNO",
        "SCMP_ACT_KILL",
        "SCMP_ACT_KILL_PROCESS",
        "SCMP_ACT_KILL_THREAD",
        "SCMP_ACT_TRAP",
    }
)
"""The default actions that deny a call. A profile that defaults to allow is refused."""


@dataclass(frozen=True)
class SeccompPlan:
    """One host source's profile: its file (`path`, named by the hash of `content`) and bytes."""

    path: Path
    content: bytes


def _source_error(source: Path, detail: str) -> GinnError:
    return make("GINN-E-SECCOMP-SOURCE", source=str(source), detail=detail)


def read_source(source: Path) -> bytes:
    """The bytes of the host profile. A missing or unreadable file gives GINN-E-SECCOMP-SOURCE."""
    try:
        return source.read_bytes()
    except OSError as exc:
        raise _source_error(source, f"cannot be read ({exc.strerror or exc})") from exc


def _rules(parsed: dict[str, Any], source: Path) -> list[dict[str, Any]]:
    """The syscall rules, each checked to carry a `names` list that ginn can read."""
    raw = parsed.get("syscalls")
    if not isinstance(raw, list):
        raise _source_error(source, "has no list of syscall rules")
    rules: list[dict[str, Any]] = []
    for rule in raw:
        if not isinstance(rule, dict):
            raise _source_error(source, "has a syscall rule that is not an object")
        if "name" in rule:
            raise _source_error(source, "uses the single 'name' field, which ginn cannot check")
        names = rule.get("names")
        if not isinstance(names, list) or not all(isinstance(name, str) for name in names):
            raise _source_error(source, "has a syscall rule with no list of names")
        rules.append(rule)
    return rules


def build_profile(data: bytes, source: Path = DEFAULT_SOURCE) -> bytes:
    """The sethostname-only profile of `data`, as JSON bytes (see the module docstring)."""
    try:
        parsed: Any = json.loads(data)
    except ValueError as exc:
        raise _source_error(source, "is not valid JSON") from exc
    if not isinstance(parsed, dict):
        raise _source_error(source, "is not a JSON object")
    if parsed.get("defaultAction") not in DENY_ACTIONS:
        raise _source_error(source, "does not default to a deny action")
    kept: list[dict[str, Any]] = []
    named = 0
    for rule in _rules(parsed, source):
        names: list[str] = rule["names"]
        if SETHOSTNAME not in names:
            kept.append(rule)
            continue
        named += 1
        remaining = [name for name in names if name != SETHOSTNAME]
        if remaining:
            kept.append({**rule, "names": remaining})
    if named == 0:
        raise _source_error(source, f"names no {SETHOSTNAME} rule to relax")
    allow = {
        "names": [SETHOSTNAME],
        "action": "SCMP_ACT_ALLOW",
        "args": [],
        "comment": ALLOW_COMMENT,
        "includes": {},
        "excludes": {},
    }
    parsed["syscalls"] = [allow, *kept]
    return (json.dumps(parsed, indent=2) + "\n").encode("utf-8")


def plan(seccomp_dir: Path, source: Path = DEFAULT_SOURCE) -> SeccompPlan:
    """Read `source` and plan its profile under `seccomp_dir`. It writes nothing."""
    content = build_profile(read_source(source), source)
    name = hashlib.sha256(content).hexdigest() + ".json"
    return SeccompPlan(path=seccomp_dir / name, content=content)


def write(profile: SeccompPlan, seccomp_dir: Path) -> Path:
    """Make the profile file if it is absent, or repair it if it differs, and return its path.

    The directory is an Owned Path (DR-010), made with the owned mode, and it must not be a link.
    The file must be a regular file: a link, or anything else, is refused, and its target is never
    followed. A regular file whose bytes equal the plan is kept. One that differs is replaced
    atomically, so the realm never reads a partial profile.
    """
    if seccomp_dir.is_symlink():
        raise _source_error(seccomp_dir, "the profile directory is a link, not a directory")
    seccomp_dir.mkdir(mode=OWNED_DIR_MODE, parents=True, exist_ok=True)
    try:
        status = os.lstat(profile.path)
    except FileNotFoundError:
        write_bytes_atomic(profile.path, profile.content)
        return profile.path
    if not stat.S_ISREG(status.st_mode):
        raise _source_error(profile.path, "the profile path is not a regular file")
    if profile.path.read_bytes() != profile.content:
        write_bytes_atomic(profile.path, profile.content)
    return profile.path


